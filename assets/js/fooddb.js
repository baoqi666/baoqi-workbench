 var PREFIX = /^(早饭|早餐|早|午饭|午餐|午|晚饭|晚餐|晚|加餐|加|下午茶|饮品|夜宵|夜)[ ·•・]*/;
 function norm(s) {
  return (s || '').toLowerCase().replace(/\s+/g, '').replace(/[·•・]/g, '');
 }
 function stripPrefix(q) { return (q || '').replace(PREFIX, ''); }

 function search(qRaw) {
  var q = norm(stripPrefix(qRaw));
  if (!q) return [];
  var res = [];
  for (var i = 0; i < FOODS.length; i++) {
   var f = FOODS[i];
   var keys = [f.n].concat(f.a || []);
   var best = 0;
   for (var j = 0; j < keys.length; j++) {
    var k = norm(keys[j]);
    if (!k) continue;
    if (q === k) best = Math.max(best, 100);
    else if (k.indexOf(q) >= 0 && q.length >= 1) best = Math.max(best, q.length >= 2 ? 85 : 0);
    else if (q.indexOf(k) >= 0 && k.length >= 2) best = Math.max(best, 80);
   }
   if (!best) {
    var name2 = norm(f.n);
    for (var p = 0; p + 1 < name2.length; p++) {
     if (q.indexOf(name2.substr(p, 2)) >= 0) { best = Math.max(best, 50); break; }
    }
   }
   if (best) res.push({ name: f.n, k: f.k, u: f.u || '份', score: best });
  }
  res.sort(function (a, b) { return b.score - a.score; });
  return res.slice(0, 6);
 }

 function best(qRaw) {
  var r = search(qRaw);
  return r.length ? r[0] : null;
 }

 global.FoodDB = { FOODS: FOODS, search: search, best: best };
